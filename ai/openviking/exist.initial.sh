#!/usr/bin/env bash
# openviking — pre-startup init: write ov.conf into the data volume.
#
# Runs on the host (needs no container tooling). Called every `./existential.sh run`;
# skips silently if ov.conf already exists — delete it to regenerate.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

if [[ "${IN_CONTAINER:-}" == "1" ]]; then
    exit 0
fi

# shellcheck source=.env
source "${SCRIPT_DIR}/.env"

# existential.sh exports .env.shared before running initials; source it anyway so
# `./existential.sh run openviking` works on its own. The endpoint comes from the
# EMBED role, not the global one: embeddings are a small model under high call
# volume, so they are the first thing worth moving to a second box.
if [[ -f "${REPO_ROOT}/.env.shared" ]]; then
    set -a
    # shellcheck disable=SC1091
    source "${REPO_ROOT}/.env.shared"
    set +a
fi
# shellcheck source=../../src/utils/model-endpoints.sh
source "${REPO_ROOT}/src/utils/model-endpoints.sh"
EMBED_URL="$(endpoint_for embed)"

# ── Automation output directory ───────────────────────────────────────────────
# The workspace_data volume is the knowledgebase: the same tree hermes,
# code-server and Nextcloud share, so everything you work on is indexed without
# a second directory to keep in step.
#
# generate-compose.ts already creates the volume on a full run, but
# `./existential.sh run openviking` skips that, so create it here too, along
# with the ai/ subdirectory the agent automations write into. The README is
# seeded only when absent — this is the user's directory, not ours.
WORKSPACE_DIR="${REPO_ROOT}/volumes/workspace_data"
mkdir -p "${WORKSPACE_DIR}/ai"
if [[ ! -e "${WORKSPACE_DIR}/ai/README.md" ]]; then
    cat > "${WORKSPACE_DIR}/ai/README.md" << 'AIEOF'
# workspace/ai/ — automation output

The agent automations write here. Everything in this directory was generated by
a routine, not by you, so treat it as output: read it, move what is worth keeping
somewhere else, delete the rest.

Two rules make this directory work, and they pull in opposite directions on
purpose:

- It **is** indexed into OpenViking, along with the rest of `workspace/`. Past
  output is searchable, so an agent can find and build on what an earlier run
  produced.
- Writing here starts nothing unless a file handler in
  `.decree/handlers.yml` matches it: keep handler patterns off `ai/` and an
  answer cannot trigger another run. Your desktop client still downloads it
  like any other folder.

Delete this README once you have your bearings — nothing regenerates it while
it exists, and nothing depends on it.
AIEOF
    echo "[openviking] workspace/ai/ output directory created."
fi

DATA_DIR="${REPO_ROOT}/volumes/openviking_data"
mkdir -p "${DATA_DIR}"

CONF="${DATA_DIR}/ov.conf"
if [[ -f "${CONF}" ]]; then
    # ov.conf is the user's once written — except for the embedding endpoint,
    # which is EXIST_MODEL_URL_EMBED's to own. Without this, moving embeddings to
    # another host leaves openviking retrying a dead address, and the only symptom
    # is "Failed to generate embedding: Connection error" deep in its logs.
    # "api_key": "local" is the mark of a block this script wrote; a user who
    # points openviking at a hosted provider replaces it with a real key.
    have_base=$(grep -m1 '"api_base"' "${CONF}" \
        | sed -E 's/.*"api_base"[[:space:]]*:[[:space:]]*"([^"]*)".*/\1/' || true)
    if [[ "${have_base}" == "${EMBED_URL}" ]]; then
        echo "[openviking] ov.conf exists — skipping (delete to regenerate)."
    elif grep -qE '"api_key"[[:space:]]*:[[:space:]]*"local"' "${CONF}"; then
        echo "[openviking] ov.conf api_base=${have_base} but the embed endpoint is ${EMBED_URL} — reconciling."
        # provider "ollama" is the openai embedder plus an ollama preflight, which
        # would probe whatever non-ollama server the endpoint now names.
        sed -i -E -e "s#\"api_base\"[[:space:]]*:[[:space:]]*\"[^\"]*\"#\"api_base\": \"${EMBED_URL}\"#" \
            -e 's#"provider"[[:space:]]*:[[:space:]]*"ollama"#"provider": "openai"#' "${CONF}"
    else
        echo "[openviking] ov.conf api_base=${have_base} (not one this script wrote) — leaving it alone."
    fi
    exit 0
fi

cat > "${CONF}" << EOF
{
  "embedding": {
    "dense": {
      "provider": "openai",
      "api_key": "local",
      "api_base": "${EMBED_URL}",
      "model": "${OPENVIKING_EMBEDDING_MODEL}",
      "dimension": ${OPENVIKING_EMBEDDING_DIM}
    }
  },
  "storage": {
    "workspace": "/app/.openviking/data"
  },
  "server": {
    "host": "0.0.0.0",
    "port": 1933,
    "auth_mode": "api_key",
    "root_api_key": "${OPENVIKING_API_KEY}",
    "cors_origins": ["*"]
  },
  "memory": {
    "version": "v2"
  }
}
EOF

echo "[openviking] ov.conf written."
